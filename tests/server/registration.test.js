  assert.equal((await f.request('PATCH', '/api/admin/mail', { expected_revision:1, mail }, admin)).status, 409);
  assert.equal((await f.request('PATCH', '/api/admin/payment', { expected_revision:1, providers:{stripe:{secret_key:'sk_test_other',webhook_secret:'whsec_other'}} }, admin)).status, 409);
  const settings = await f.request('GET', '/api/admin/mail', undefined, admin);
  const payment = await f.request('GET', '/api/admin/payment', undefined, admin);
